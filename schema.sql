CREATE TABLE IF NOT EXISTS usuarios (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre TEXT NOT NULL,
  apellidos TEXT NOT NULL,
  distrito TEXT NOT NULL,
  email TEXT NOT NULL UNIQUE CHECK (email = lower(email)),
  password_hash TEXT NOT NULL,
  rol TEXT NOT NULL DEFAULT 'ciudadano' CHECK (rol IN ('ciudadano', 'entidad'))
);

ALTER TABLE usuarios
  ADD COLUMN IF NOT EXISTS rol TEXT NOT NULL DEFAULT 'ciudadano'
  CHECK (rol IN ('ciudadano', 'entidad'));

CREATE TABLE IF NOT EXISTS entidades (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  usuario_id BIGINT NOT NULL UNIQUE REFERENCES usuarios(id) ON DELETE CASCADE,
  nombre TEXT NOT NULL,
  tipo TEXT NOT NULL,
  plan TEXT NOT NULL DEFAULT 'Básico' CHECK (plan IN ('Básico', 'Institucional')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS publicaciones (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  usuario_id BIGINT NOT NULL REFERENCES usuarios(id) ON DELETE CASCADE,
  categoria TEXT NOT NULL,
  marca TEXT NOT NULL DEFAULT '',
  antiguedad TEXT NOT NULL DEFAULT '',
  descripcion TEXT NOT NULL CHECK (char_length(descripcion) BETWEEN 1 AND 1000),
  condicion TEXT NOT NULL CHECK (
    condicion IN ('Operativo', 'Requiere reparación', 'No reutilizable')
  ),
  estado TEXT NOT NULL DEFAULT 'activa'
    CHECK (estado IN ('activa', 'entregada')),
  fotos JSONB NOT NULL DEFAULT '[]'::jsonb CHECK (
    jsonb_typeof(fotos) = 'array' AND jsonb_array_length(fotos) <= 3
  ),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

ALTER TABLE publicaciones
  ADD COLUMN IF NOT EXISTS estado TEXT NOT NULL DEFAULT 'activa'
  CHECK (estado IN ('activa', 'entregada'));

CREATE INDEX IF NOT EXISTS publicaciones_created_at_idx
  ON publicaciones (created_at DESC);

CREATE TABLE IF NOT EXISTS conversaciones (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  publicacion_id BIGINT NOT NULL REFERENCES publicaciones(id) ON DELETE CASCADE,
  interesado_id BIGINT NOT NULL REFERENCES usuarios(id) ON DELETE CASCADE,
  dueno_id BIGINT NOT NULL REFERENCES usuarios(id) ON DELETE CASCADE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT conversaciones_participantes_distintos
    CHECK (interesado_id <> dueno_id),
  CONSTRAINT conversaciones_unicas_por_interesado
    UNIQUE (publicacion_id, interesado_id)
);

CREATE TABLE IF NOT EXISTS mensajes (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  conversacion_id BIGINT NOT NULL REFERENCES conversaciones(id) ON DELETE CASCADE,
  autor_id BIGINT NOT NULL REFERENCES usuarios(id) ON DELETE CASCADE,
  texto TEXT NOT NULL CHECK (char_length(texto) BETWEEN 1 AND 1000),
  leido BOOLEAN NOT NULL DEFAULT FALSE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

ALTER TABLE mensajes
  ADD COLUMN IF NOT EXISTS leido BOOLEAN NOT NULL DEFAULT FALSE;

CREATE INDEX IF NOT EXISTS mensajes_conversacion_created_at_idx
  ON mensajes (conversacion_id, created_at, id);

CREATE TABLE IF NOT EXISTS puntos_acopio (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  entidad_id BIGINT NOT NULL REFERENCES entidades(id) ON DELETE CASCADE,
  nombre TEXT NOT NULL CHECK (char_length(nombre) BETWEEN 1 AND 150),
  direccion TEXT NOT NULL CHECK (char_length(direccion) BETWEEN 1 AND 150),
  distrito TEXT NOT NULL CHECK (char_length(distrito) BETWEEN 1 AND 150),
  horario TEXT NOT NULL DEFAULT '' CHECK (char_length(horario) <= 150),
  categorias JSONB NOT NULL DEFAULT '[]'::jsonb CHECK (
    jsonb_typeof(categorias) = 'array'
  ),
  lat DOUBLE PRECISION NOT NULL CHECK (lat BETWEEN -18.5 AND 0),
  lng DOUBLE PRECISION NOT NULL CHECK (lng BETWEEN -81.5 AND -68),
  activo BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS puntos_acopio_activos_idx
  ON puntos_acopio (activo, entidad_id);
